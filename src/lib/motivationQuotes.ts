// Günün tarihine göre deterministik olarak o günün sözünü döndüren fonksiyon
// Böylece aynı gün içinde sayfa yenilense de değişmez, ertesi gün gece yarısı otomatik değişir.
export function getDailyMotivationQuote(grade: string, date: Date = new Date()): MotivationQuote {
  const g = (grade || '').toLowerCase().trim();
  
  // Günlük tohum hesabı (Yılın günü + yıl)
  const startOfYear = new Date(date.getFullYear(), 0, 0);
  const diff = date.getTime() - startOfYear.getTime();
  const dayOfYear = Math.floor(diff / (1000 * 60 * 60 * 24));
  const seed = dayOfYear + date.getFullYear() * 365;

  let quoteList: MotivationQuote[];

  // Yaş / Sınıf Seviyesi Tespiti
  if (g.includes('8') || g.includes('lgs')) {
    quoteList = MOTIVATION_QUOTES_LGS;
  } else if (g.includes('9') || g.includes('10') || g.includes('maarif')) {
    quoteList = MOTIVATION_QUOTES_MAARIF;
  } else if (g.includes('11') || g.includes('12') || g.includes('yks') || g.includes('mezun')) {
    quoteList = MOTIVATION_QUOTES_YKS;
  } else if (g.includes('5') || g.includes('6') || g.includes('7') || g.includes('ortaokul')) {
    quoteList = MOTIVATION_QUOTES_ORTAOKUL;
  } else {
    // Genel lise/öğrenci varsayılanı
    quoteList = MOTIVATION_QUOTES_MAARIF;
  }

  const index = Math.abs(seed) % quoteList.length;
  return quoteList[index];
}

// Yaş grubuna göre grup etiketini veren yardımcı fonksiyon
export function getAgeGroupBadge(grade: string): { label: string; ageRange: string; color: string } {
  const g = (grade || '').toLowerCase().trim();

  if (g.includes('8') || g.includes('lgs')) {
    return {
      label: 'LGS Hedef Motivasyonu',
      ageRange: '8. Sınıf • 13-14 Yaş',
      color: 'bg-primary/10 text-primary border-primary/20'
    };
  }
  if (g.includes('9') || g.includes('10') || g.includes('maarif')) {
    return {
      label: 'Maarif & Lise Vizyonu',
      ageRange: `${g.includes('10') ? '10' : '9'}. Sınıf • 14-16 Yaş`,
      color: 'bg-amber-500/10 text-amber-700 border-amber-500/20'
    };
  }
  if (g.includes('11') || g.includes('12') || g.includes('yks') || g.includes('mezun')) {
    return {
      label: 'YKS & Gelecek İnşası',
      ageRange: `${g.includes('11') ? '11. Sınıf' : g.includes('12') ? '12. Sınıf' : 'Mezun'} • 16-19 Yaş`,
      color: 'bg-secondary/10 text-secondary border-secondary/20'
    };
  }
  if (g.includes('5') || g.includes('6') || g.includes('7') || g.includes('ortaokul')) {
    const num = g.includes('5') ? '5' : g.includes('6') ? '6' : '7';
    return {
      label: 'Öğrenme & Keşif Neşesi',
      ageRange: `${num}. Sınıf • 10-13 Yaş`,
      color: 'bg-emerald-500/10 text-emerald-800 border-emerald-500/20'
    };
  }
  return {
    label: 'Günün İlhamı',
    ageRange: 'Genel Gelişim',
    color: 'bg-primary/10 text-primary border-primary/20'
  };
}
